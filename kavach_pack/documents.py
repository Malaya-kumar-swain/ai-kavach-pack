"""Write the governance pack: Markdown documents filled in from the system form."""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

from .form import System, lang_names
from .gaps import Gap, blockers, check
from .tiering import TIER_NAMES, factors, tier

DISCLAIMER = "> Generated by AI-Kavach-Pack. Guidance for an internal review, not legal advice."

YES, NO, ASK = "Yes", "**No**", "Unknown"


def _yn(value: bool) -> str:
    return YES if value else NO


def _inr(value: int | None) -> str:
    return f"Rs {value:,}" if value is not None else "Not set"


def risk_tier_doc(s: System) -> str:
    t = tier(s)
    rows = "\n".join(f"| {f.name} | {f.score} ({TIER_NAMES[f.score]}) | {f.reason} |" for f in factors(s))
    return f"""# Risk tier: {s.name}

{DISCLAIMER}

**Tier: {TIER_NAMES[t]}.** The highest factor sets the tier; one high-risk factor makes the whole system high risk.

| Factor | Score | Why |
|---|---|---|
{rows}

## Re-tier when
- the system gets a new tool or a new kind of action
- it moves from internal use to customers or the public
- it starts using a new kind of personal data
- a serious incident happens
"""


def system_card_doc(s: System) -> str:
    return f"""# System card: {s.name}

{DISCLAIMER}

| | |
|---|---|
| Purpose | {s.purpose} |
| Business owner | {s.owner} |
| Status | {s.status} |
| Risk tier | {TIER_NAMES[tier(s)]} |
| Who uses it | {s.audience}, about {s.users:,} users{', including vulnerable users' if s.vulnerable_users else ''} |
| What the AI does | {s.role}{(': ' + ', '.join(s.actions)) if s.actions else ''} |
| Domain | {s.domain} |
| Model | {s.model or 'Not stated'} from {s.provider or 'not stated'} |
| Where it runs / stores data | inference: {s.inference_location}, storage: {s.storage_location} |
| Personal data | {', '.join(s.data_kinds) if s.personal_data else 'None'} |
| Where personal data can end up | {', '.join(s.stores) or 'Not stated'} |
| Languages supported | {lang_names(s.languages)} |
| Languages quality-tested | {lang_names(s.quality_tested_languages) or 'None'} |
| Human approval for actions | {s.human_approval if s.role == 'acts' else 'Not applicable'} |
| Action limit | {_inr(s.action_limit_inr) if s.role == 'acts' else 'Not applicable'} |
| Kill switch | {_yn(s.kill_switch) if s.role == 'acts' else 'Not applicable'} |
| Hand-over to a person | {_yn(s.fallback_to_human)} |
| Incident owner | {s.incident_owner or '**Not named**'} |
| Monthly budget | {_inr(s.monthly_budget_inr)} |

## Known limits
Write the cases this system must not handle, and what it does instead.
"""


def dpdp_doc(s: System) -> str:
    if not s.personal_data:
        return f"""# DPDP checklist: {s.name}

{DISCLAIMER}

The form says this system uses **no personal data**. Re-check this if prompts, documents or logs can contain names,
phone numbers, IDs or account details, because users often paste them in.
"""
    places = {
        "vector-store": "Vector store / embeddings: can one person's data be found and deleted?",
        "cache": "Response cache: are cached answers with personal data purged on erasure?",
        "logs": "Prompt and output logs: is personal data masked and kept only as long as needed?",
        "agent-memory": "Agent memory: can a person's memories be listed and deleted?",
        "fine-tune": "Fine-tuned model: was personal data used to train it, and how is erasure honoured?",
    }
    store_rows = "\n".join(f"| {places[x]} | {_yn(s.erasure_tested)} |" for x in s.stores) or "| No stores listed | |"
    children = ("\n## Children (s.9)\n- [ ] Verifiable parental consent is obtained.\n"
                "- [ ] No tracking, behavioural monitoring or targeted advertising directed at children.\n"
                if "children" in s.data_kinds else "")
    return f"""# DPDP checklist: {s.name}

{DISCLAIMER}
> Section numbers refer to the Digital Personal Data Protection Act, 2023. Confirm current obligations, timelines
> and sector rules with your legal team.

Personal data used: {', '.join(s.data_kinds) or 'not listed'}.

| Duty | Status |
|---|---|
| Lawful basis recorded for this purpose (s.4, s.6, s.7) | {s.lawful_basis if s.lawful_basis != 'none-recorded' else NO} |
| Notice covers the AI use, in plain language (s.5) | {_yn(s.notice_covers_ai)} |
| Withdrawal of consent stops the AI using the data (s.6) | {'Check' if s.lawful_basis == 'consent' else 'Not applicable'} |
| Retention period set; data erased when the purpose is served (s.8(7)) | {f'{s.retention_days} days' if s.retention_days is not None else NO} |
| Reasonable security safeguards, including vendors (s.8(5)) | {'Check' if s.injection_tested else NO + ' (no injection or leak testing yet)'} |
| Breach process covers AI incidents (s.8(6)) | {'Check' if s.incident_owner else NO + ' (no incident owner)'} |
| Access, correction and erasure work for this system (s.11, s.12) | {_yn(s.erasure_tested)} |
| Grievance route visible to users (s.13) | Check |
| Transfer outside India allowed (s.16 and sector rules) | {'Check with legal' if 'outside-india' in (s.inference_location, s.storage_location) else 'Stays in India' if s.inference_location == s.storage_location == 'india' else ASK} |
{children}
## Where personal data can hide in this system

| Place | Erasure tested |
|---|---|
{store_rows}

## Evidence to keep
- Consent or legitimate-use records, with the notice version and purpose
- Erasure logs with proof of deletion for each store above
- Leakage and injection test reports
- Vendor data-processing terms
"""


def vendor_doc(s: System) -> str:
    known = {
        "train": {"yes": "Yes: **red flag**", "no": "No (get it in writing)", "unknown": "Unknown: **ask**"}[s.vendor_trains_on_data],
        "where": f"inference {s.inference_location}, storage {s.storage_location}",
        "retention": f"{s.vendor_retention_days} days" if s.vendor_retention_days is not None else "Unknown: ask",
    }
    return f"""# Vendor questions: {s.provider or 'model provider'} ({s.model or 'model not stated'})

{DISCLAIMER}

Ask for evidence, not only answers. What the form already says is shown on the right.

| # | Question | Known so far |
|---|---|---|
| 1 | Do you store our prompts and outputs? For how long, and in which countries? | {known['retention']}; {known['where']} |
| 2 | Do you use our data to train or improve any model? Can the contract switch that off? | {known['train']} |
| 3 | Who at your company or your sub-processors can see our data? | |
| 4 | How do you delete our data on request, and how do you prove it? | |
| 5 | Can inference and storage stay in India if we need that? | {known['where']} |
| 6 | Which independent certifications or audits do you hold? Can we see the reports? | |
| 7 | How do you protect against prompt injection and data leakage? | |
| 8 | How fast will you notify us of a security incident? | |
| 9 | What evidence do you have for quality in {lang_names(s.languages)}? | |
| 10 | Will you notify us before changing or retiring this model? | |
| 11 | What are the rate limits and price at our expected volume? | |
| 12 | Can we export our data, prompts and configurations if we leave? | |
| 13 | Who owns outputs and anything fine-tuned on our data? | |

## Red flags
- No clear answer on training with customer data
- No way to keep data in India when your sector requires it
- No advance notice of model changes
- No evidence for claims about Indian-language quality
"""


def prelaunch_doc(s: System, gaps: list[Gap]) -> str:
    t = tier(s)
    open_ids = {x.id for x in gaps}

    def line(min_tier: int, text: str, done: bool) -> str | None:
        return f"- [{'x' if done else ' '}] {text}" if t >= min_tier else None

    lines = [
        "## Quality",
        line(1, "Test set of realistic questions with expected answers, owned by the business", False),
        line(2, f"Quality measured in every supported language ({lang_names(s.languages)})", "QUALITY-LANG" not in open_ids),
        line(3, "Human-review sample of live outputs planned for the first 30 days", False),
        "## Safety and security",
        line(2, "Domain limits written in plain words and enforced by guardrails", s.guardrails),
        line(2, "Prompt-injection testing, including instructions hidden in documents", s.injection_tested),
        line(3, "Injection and data-leak testing in each supported language and script", "SEC-INJECTION-LANG" not in open_ids and s.injection_tested),
        line(3, "Red-team exercise completed, findings fixed or accepted", s.red_team),
    ]
    if s.role == "acts":
        lines += ["## Agent actions",
                  line(1, f"Written limit on actions ({_inr(s.action_limit_inr)})", s.action_limit_inr is not None),
                  line(1, f"Human approval for risky actions (now: {s.human_approval})", s.human_approval != "none"),
                  line(1, "Tested behaviour when tools fail, including lost responses that could cause duplicates", False),
                  line(1, "Kill switch exists and has been tested", s.kill_switch)]
    lines += ["## Privacy",
              line(1, "DPDP checklist completed (03-dpdp-checklist.md)", not any(x.id.startswith("DPDP") for x in gaps)),
              line(2, "Erasure tested across every store", s.erasure_tested or not s.stores),
              "## Operations",
              line(1, f"Owner and incident contact named ({s.incident_owner or 'missing'})", bool(s.incident_owner)),
              line(2, "Monitoring of usage, quality, cost and errors", s.monitoring),
              line(2, f"Monthly budget agreed ({_inr(s.monthly_budget_inr)})", s.monthly_budget_inr is not None),
              line(3, "Rollback plan tested", s.rollback_plan),
              line(1, "Entry added to the AI inventory", False)]
    body = "\n".join(x if x.startswith("-") else f"\n{x}" for x in lines if x)
    return f"""# Pre-launch checklist: {s.name} ({TIER_NAMES[t]} tier)

{DISCLAIMER}

Ticked lines are what the form says is done. Each line still needs evidence: a test report, a log or a named owner.
{body}
"""


def incident_doc(s: System) -> str:
    sev1 = ["Personal data or internal instructions revealed"]
    if s.role == "acts":
        sev1.append("A wrong, duplicate or unauthorised action: " + (", ".join(s.actions) or "any action"))
    if s.domain in ("finance", "health", "legal", "safety", "credit", "eligibility"):
        sev1.append(f"Harmful or clearly wrong {s.domain} guidance reaching users at scale")
    return f"""# Incident plan: {s.name}

{DISCLAIMER}

**Incident owner:** {s.incident_owner or '**Not named: fix before go-live**'}

## Severity 1 for this system (act within 1 hour)
""" + "\n".join(f"- {x}" for x in sev1) + f"""

## First hour
1. Contain: {'use the kill switch' if s.kill_switch else 'pause the feature (no kill switch recorded)'}, or switch to the safe fallback.
2. Preserve evidence: prompts, outputs, tool calls, model and prompt versions.
3. Notify the owner, CAIO, CISO and DPO. If personal data is involved, the DPO starts the breach process.
4. Size it: how many users, which data, which actions.

## Within 72 hours
5. Find the root cause: model change, prompt change, data change, new attack or tool failure.
6. Fix it, and add a test so the same failure is caught before the next release.
7. Reverse or compensate affected actions; tell affected people where required.
8. Decide with the approver whether to resume, and under what conditions.
"""


def approvals_doc(s: System) -> str:
    t = tier(s)
    who = {1: "Business owner approves; tech owner is responsible.",
           2: "Business owner approves after review by Data Protection (DPO) and Security.",
           3: "AI council (chaired by the CAIO or Head of AI) approves, after DPO, Security and Legal review. Staged rollout."}[t]
    return f"""# Approvals: {s.name}

{DISCLAIMER}

**{TIER_NAMES[t]} tier.** {who}

The approver should be able to answer, in one sentence each: what can go wrong, how we would know, and how we would stop it.

| Role | Name | Date | Conditions |
|---|---|---|---|
| Business owner | {s.owner} | | |
| Tech owner | | | |
""" + ("| DPO | | | |\n| Security | | | |\n" if t >= 2 else "") + ("| Legal | | | |\n| AI council | | | |\n" if t >= 3 else "")


def summary_doc(s: System, gaps: list[Gap]) -> str:
    t = tier(s)
    top = sorted(factors(s), key=lambda f: -f.score)[:3]
    blk = blockers(gaps)
    warn = [x for x in gaps if x.severity == "warning"]
    blk_lines = "\n".join(f"- **{x.area}:** {x.message}" for x in blk) or "- None"
    decision = "Not ready for go-live: fix the blockers or have the approver formally accept them." if blk else \
        "Ready for the approval step, subject to evidence for each checklist line."
    return f"""# {s.name}: one-page summary

{DISCLAIMER}

| | |
|---|---|
| Purpose | {s.purpose} |
| Owner | {s.owner} |
| Status | {s.status} |
| **Risk tier** | **{TIER_NAMES[t]}** |
| Main reasons | {'; '.join(f'{f.name}: {f.reason}' for f in top)} |
| Blockers | {len(blk)} |
| Warnings | {len(warn)} |

## Blockers
{blk_lines}

## Decision needed
{decision}

## Documents in this pack
1. 01-risk-tier.md
2. 02-system-card.md
3. 03-dpdp-checklist.md
4. 04-vendor-questions.md
5. 05-pre-launch-checklist.md
6. 06-incident-plan.md
7. 07-approvals.md
8. gaps.json (for CI)
"""


def build(s: System, out_dir: str | Path) -> Path:
    """Write the full pack for one system into ``out_dir/<system-slug>/``."""
    gaps = check(s)
    folder = Path(out_dir) / s.slug
    folder.mkdir(parents=True, exist_ok=True)
    docs = {
        "00-summary.md": summary_doc(s, gaps),
        "01-risk-tier.md": risk_tier_doc(s),
        "02-system-card.md": system_card_doc(s),
        "03-dpdp-checklist.md": dpdp_doc(s),
        "04-vendor-questions.md": vendor_doc(s),
        "05-pre-launch-checklist.md": prelaunch_doc(s, gaps),
        "06-incident-plan.md": incident_doc(s),
        "07-approvals.md": approvals_doc(s),
    }
    for name, text in docs.items():
        (folder / name).write_text(text, encoding="utf-8")
    (folder / "gaps.json").write_text(json.dumps({
        "system": s.name, "tier": TIER_NAMES[tier(s)], "generated": date.today().isoformat(),
        "blockers": len(blockers(gaps)), "gaps": [x.to_dict() for x in gaps]}, indent=2), encoding="utf-8")
    return folder
